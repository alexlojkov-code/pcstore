let lang = 'ru';
const listeners = new Set();

export const getLang = () => lang;

export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.ru[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function detect() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'ru' || q === 'uz') return q;
  const saved = store.get('bl.lang');
  if (saved === 'ru' || saved === 'uz') return saved;
  return (navigator.language || '').toLowerCase().startsWith('uz') ? 'uz' : 'ru';
}

// Переводит текст в разметке: data-i18n (текст), data-i18n-html (своя разметка из словаря),
// data-i18n-attr="aria-label:key;title:key2".
export function apply(root = document, vars = {}) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n, vars); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml, vars); });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim(), vars));
    }
  });
}

export function setLang(next, { save = true, vars = {} } = {}) {
  lang = next === 'uz' ? 'uz' : 'ru';
  if (save) store.set('bl.lang', lang);
  document.documentElement.lang = lang;
  apply(document, vars);
  const url = new URL(location.href);
  if (lang === 'ru') url.searchParams.delete('lang'); else url.searchParams.set('lang', lang);
  history.replaceState(history.state, '', url);
  listeners.forEach((fn) => fn(lang));
}

export const onChange = (fn) => listeners.add(fn);
